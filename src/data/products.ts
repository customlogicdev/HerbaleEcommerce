export function getProductBySlug(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function getProductById(id: string) {
  return products.find((product) => product.id === id);
}

export function getFeaturedProducts() {
  return products.filter((product) => product.featured);
}

export function getRelatedProducts(slug: string, limit = 4) {
  const current = getProductBySlug(slug);
  if (!current) return products.slice(0, limit);
  const same = products.filter((p) => p.category === current.category && p.slug !== slug);
  const extras = products.filter((p) => p.slug !== slug && p.category !== current.category);
  return [...same, ...extras].slice(0, limit);
}

export function getReviewsForProduct(productId: string) {
  const matching = reviews.filter((review) => review.productId === productId);
  if (matching.length > 0) return matching;
  return reviews.slice(0, 3);
}

export function searchProducts(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter(
    (product) =>
      product.name.toLowerCase().includes(q) ||
      product.category.includes(q) ||
      product.shortDescription.toLowerCase().includes(q) ||
      product.ingredients.some((item) => item.toLowerCase().includes(q)),
  );
}
